async function run() {
    try {
        const cat = await client.fetch('*[_type == "category" && slug.current == "local"][0]._id');
        if (!cat) {
            console.log('Error: Category "local" not found');
            return;
        }

        article.category = {
            _type: 'reference',
            _ref: cat
        };

        const result = await client.create(article);
        console.log(`Created featured article: ${result.title} (${result._id})`);
    } catch (error) {
        console.error('Error importing news:', error);
    }
}
run();
